import re
from typing import Any


def build_pull_request_payload(
    branch_name: str,
    changed_files: list[str],
    summary: str,
    base_branch: str = "main",
) -> dict[str, Any]:
    """
    Generate a GitHub-compatible pull request payload.

    Args:
        branch_name: Migration branch containing the fixes.
        changed_files: Files modified by API Guardian.
        summary: Explanation of the migration.
        base_branch: Target branch of the pull request.

    Returns:
        Dictionary containing the GitHub PR request fields.
    """

    # Validate the source branch.
    if not branch_name.startswith("api-guardian/migration-"):
        raise ValueError(
            "Invalid migration branch name."
        )

    # Reject malformed Git ref names and unsafe characters.
    if not re.fullmatch(
        r"api-guardian/migration-[a-zA-Z0-9_-]+",
        branch_name,
    ):
        raise ValueError(
            "Migration branch contains invalid characters."
        )

    # Validate the target branch.
    if not re.fullmatch(
        r"[a-zA-Z0-9][a-zA-Z0-9/_-]*",
        base_branch,
    ):
        raise ValueError(
            "Invalid target branch name."
        )

    if branch_name == base_branch:
        raise ValueError(
            "Source and target branches must be different."
        )

    # Ensure there is at least one modified file.
    if not changed_files:
        raise ValueError(
            "Cannot prepare a PR without changed files."
        )

    # Require a meaningful migration summary.
    if not summary.strip():
        raise ValueError(
            "Migration summary cannot be empty."
        )

    # Generate a Markdown list of modified files.
    file_list = "\n".join(
        f"- `{file_path}`"
        for file_path in changed_files
    )

    # Create a descriptive PR title.
    title = "fix: migrate deprecated API usage"

    # Build the PR description.
    body = f"""## Summary

{summary.strip()}

## Modified Files

{file_list}

## Changes

This pull request contains proposed API migration changes
prepared by API Guardian.

## Review Checklist

- [ ] Review generated code changes
- [ ] Verify the API migration is correct
- [ ] Run relevant tests
- [ ] Confirm backward compatibility where required

---

Generated by API Guardian.
"""

    # GitHub's create-pull-request API accepts these fields.
    return {
        "title": title,
        "body": body,
        "head": branch_name,
        "base": base_branch,
        "draft": True,
    }
