# GitHub owner/repository names should be simple path segments
OWNER_PATTERN = re.compile(r"^[A-Za-z0-9-]{1,39}$")
REPO_PATTERN = re.compile(r"^[A-Za-z0-9._-]{1,100}$")


def validate_repository(owner: str, repo: str):
    """
    Validate the repository owner and name.

    This prevents arbitrary paths or unexpected URL components
    from being passed to Git.
    """

    if not OWNER_PATTERN.fullmatch(owner):
        raise ValueError("Invalid GitHub owner name")

    if not REPO_PATTERN.fullmatch(repo):
        raise ValueError("Invalid GitHub repository name")

    if repo in {".", ".."}:
        raise ValueError("Invalid repository name")


def parse_github_repository_url(url: str) -> tuple[str, str]:
    """Accept a GitHub repository URL and return its validated owner/name."""
    parsed = urlparse(url.strip())
    if parsed.scheme not in {"https", "http"} or parsed.netloc.lower() not in {
        "github.com",
        "www.github.com",
    }:
        raise ValueError(
            "Enter a GitHub repository URL, such as https://github.com/owner/repo"
        )
    parts = [part for part in parsed.path.split("/") if part]
    if len(parts) != 2:
        raise ValueError("The GitHub URL must point directly to an owner/repository")
    owner, repo = parts
    repo = repo.removesuffix(".git")
    validate_repository(owner, repo)
    return owner, repo


def clone_repository(
    owner: str,
    repo: str,
    all_branches: bool = False,
    branch: str | None = None,
):
    """
    Clone a public GitHub repository into a temporary folder.

    Args:
        owner (str): GitHub username or organization.
        repo (str): GitHub repository name.

    Returns:
        tuple: (workspace_path, repository_path)

    Raises:
        ValueError: If the repository name is invalid.
        GitCommandError: If Git fails to clone the repository.
    """

    # Validate the user-provided repository information
    validate_repository(owner, repo)

    # Construct the HTTPS URL for the public repository
    repo_url = f"https://github.com/{owner}/{repo}.git"

    # Create a unique temporary workspace
    workspace = Path(tempfile.mkdtemp(prefix="api_guardian_"))

    # Repository will be cloned inside this folder
    repository_path = workspace / "repository"

    try:
        # Fetch all remote branch refs when the scan requests every branch.
        clone_options = {
            "depth": 1,
            "env": {"GIT_TERMINAL_PROMPT": "0"},
        }
        if all_branches:
            clone_options["multi_options"] = ["--no-single-branch"]
        elif branch:
            clone_options["branch"] = branch
        Repo.clone_from(repo_url, str(repository_path), **clone_options)

        return workspace, repository_path

    except Exception:
        # Delete the workspace if cloning fails
        shutil.rmtree(workspace, ignore_errors=True)
        raise


def list_source_files(repository_path: Path):
    """
    Find supported source code files in a repository.

    Args:
        repository_path (Path): Local cloned repository path.

    Returns:
        list: Relative paths of supported source files.
    """

    source_files = []

    # Exclude repository metadata, dependencies, generated bytecode, and
    # virtual environments. Tracked files in dist/ and build/ remain in scope.
    excluded_directories = {
        ".git",
        "node_modules",
        "__pycache__",
        ".tox",
        ".nox",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
    }

    # Recursively search through repository files
    for file_path in repository_path.rglob("*"):
        # Skip directories and symbolic links
        if not file_path.is_file() or file_path.is_symlink():
            continue

        # Determine the path relative to the repository root
        relative_path = file_path.relative_to(repository_path)

        # Skip excluded directories
        if any(
            part in excluded_directories
            or part in {"venv", "env", ".env"}
            or part.startswith(".venv")
            for part in relative_path.parts
        ):
            continue

        # Include only supported programming languages
        if file_path.suffix.lower() in SUPPORTED_EXTENSIONS:
            source_files.append(str(relative_path))

    # Sort results to make the response easier to read
    return sorted(source_files)


def repository_branches(repository_path: Path) -> list[str]:
    """Return all fetched remote branches, excluding the symbolic HEAD ref."""
    repository = Repo(repository_path)
    if "origin" not in [remote.name for remote in repository.remotes]:
        return [repository.active_branch.name]
    branches = sorted(
        {
            ref.remote_head
            for ref in repository.remotes.origin.refs
            if ref.remote_head != "HEAD"
        }
    )
    return branches or [repository.active_branch.name]


def checkout_repository_branch(repository_path: Path, branch: str) -> None:
    """Checkout a fetched branch after verifying it exists in this clone."""
    repository = Repo(repository_path)
    remote_refs = (
        {
            ref.remote_head: ref
            for ref in repository.remotes.origin.refs
            if ref.remote_head != "HEAD"
        }
        if "origin" in [remote.name for remote in repository.remotes]
        else {}
    )
    if branch in remote_refs:
        repository.git.checkout("-B", branch, remote_refs[branch].name)
    elif branch in repository.heads:
        repository.git.checkout(branch)
    else:
        raise ValueError(f"Branch '{branch}' was not found in the repository")


def cleanup_workspace(workspace: Path):
    """
    Delete a temporary repository workspace.

    Args:
        workspace (Path): Temporary workspace to delete.
    """

    # Remove the temporary directory and its contents
    shutil.rmtree(workspace, ignore_errors=True)
